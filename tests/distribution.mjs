import {readFile,writeFile,mkdir,mkdtemp,copyFile,readdir} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {resolve,join} from 'node:path';
import {tmpdir} from 'node:os';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=resolve(import.meta.dirname,'..'),source=resolve(process.argv[2]??join(root,'dist'));
const output=resolve(process.env.EVIDENCE_DIR??join(root,'artifacts/distribution'));
await mkdir(output,{recursive:true});
const staging=await mkdtemp(join(tmpdir(),'facility-3d-distribution-'));
const hash=data=>createHash('sha256').update(data).digest('hex');
const exe=await readFile(join(source,'FacilityEscape.exe'));
const dll=await readFile(join(source,'gua_godot.windows.release.x86_64.dll'));
const official=await readFile(join(root,'addons/gua/bin/gua_godot.windows.release.x86_64.dll'));
function amd64(data){assert.equal(data.toString('ascii',0,2),'MZ');const pe=data.readUInt32LE(0x3c);assert.equal(data.toString('ascii',pe,pe+4),'PE\0\0');assert.equal(data.readUInt16LE(pe+4),0x8664);}
amd64(exe);amd64(dll);assert.equal(hash(dll),hash(official),'DLL equals verified official Gua 1.1.2 asset');
assert.equal(exe.toString('ascii',exe.length-4),'GDPC','embedded pack footer');
const packSize=Number(exe.readBigUInt64LE(exe.length-12)),packOffset=exe.length-12-packSize;
assert.ok(packOffset>1024*1024&&packSize>1024&&packOffset+packSize+12===exe.length);
assert.equal(exe.toString('ascii',packOffset,packOffset+4),'GDPC','embedded pack header');
assert.equal(exe.readUInt32LE(packOffset+8),4);assert.equal(exe.readUInt32LE(packOffset+12),7);
for(const name of ['FacilityEscape.exe','gua_godot.windows.release.x86_64.dll'])await copyFile(join(source,name),join(staging,name));
assert.deepEqual((await readdir(staging)).sort(),['FacilityEscape.exe','gua_godot.windows.release.x86_64.dll'].sort());
const report={source,staging,exeSha256:hash(exe),dllSha256:hash(dll),officialDllMatch:true,peArchitecture:'AMD64',packSize,packOffset,files:await readdir(staging),cleanDirectoryAcceptancePassed:false};
await writeFile(join(output,'integrity.json'),JSON.stringify(report,null,2));
const child=spawn(process.execPath,[join(root,'tests/acceptance.mjs'),join(staging,'FacilityEscape.exe')],{cwd:staging,env:{...process.env,TEST_SUITE:'normal',HEADED:'0',SAVE_APPDATA:join(output,'appdata'),EVIDENCE_DIR:output,GUA_TEST_CWD:staging,GUA_NATIVE_DIR:'',GUA_RUNTIME_NATIVE_DIR:''},windowsHide:true,stdio:'inherit'});
const code=await new Promise((res,rej)=>{child.on('error',rej);child.on('exit',res);});
report.cleanDirectoryAcceptancePassed=code===0;
await writeFile(join(output,'integrity.json'),JSON.stringify(report,null,2));
assert.equal(code,0,'real EXE acceptance with only two distribution files and isolated cwd');
console.log(JSON.stringify(report));
